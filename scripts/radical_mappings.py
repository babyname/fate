def fix_radical_from_number(radical_str, is_traditional=False):
    """Extract number from radical like "187'" and map to proper radical char."""
    if not radical_str:
        return None, 0
    
    # Try to extract number
    import re
    match = re.match(r"(\d+)", radical_str.strip())
    if not match:
        return None, 0
    
    num = int(match.group(1))
    
    table = KANGXI_TRAD if is_traditional else KANGXI_TABLE
    
    if num in table:
        char, stroke = table[num]
        return char, stroke
    
    return None, 0

def get_unicode_code_point(char):
    """Generate U+XXXX unicode code point for a character."""
    if not char or len(char) == 0:
        return ""
    cp = ord(char[0])
    return f"U+{cp:04X}"
