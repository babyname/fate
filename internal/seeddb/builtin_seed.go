func BuiltinWuXingSeeds() []SeedWuXing {
	elements := []string{"金", "木", "水", "火", "土"}
	result := make([]SeedWuXing, 0, 125)
	id := 1
	for _, first := range elements {
		for _, second := range elements {
			for _, third := range elements {
				key := first + second + third
				fortune, _ := wuxing.GetWuXing(key)
				result = append(result, SeedWuXing{
					ID:      id,
					First:   first,
					Second:  second,
					Third:   third,
					Fortune: fortune,
				})
				id++
			}
		}
	}
	return result
}
