func sc(char, pinyin, wuxing, radical string, kangxiStroke, commonLevel int, genderHint, meaning string) SeedCharacter {
	return SeedCharacter{
		Char:          char,
		Pinyin:        []string{pinyin},
		WuXing:        wuxing,
		KangxiStroke:  kangxiStroke,
		ScienceStroke: kangxiStroke,
		Radical:       radical,
		Regular:       true,
		Nameable:      true,
		IsSimplified:  true,
		CommonLevel:   commonLevel,
		GenderHint:    genderHint,
		Meaning:       meaning,
		Source:        "builtin",
	}
}

func BuiltinCharacterSeeds() []SeedCharacter {
	seen := make(map[string]bool)
	var result []SeedCharacter
	for _, s := range append(surnameSeeds(), namingSeeds()...) {
		if !seen[s.Char] {
			seen[s.Char] = true
			result = append(result, s)
		}
	}
	return result
}

