func GetKangxiRadicalStroke(radical string) int {
	if s, ok := kangxiRadicalStrokes[radical]; ok {
		return s
	}
	return 0
}

func GetScienceStrokeCorrection(char rune) (int, bool) {
	if c, ok := kangxiStrokeCorrections[char]; ok {
		return c.CorrectedStroke, true
	}
	return 0, false
}

func ApplyKangxiCorrections(entries []*CharEntry) int {
	updated := 0
	for _, e := range entries {
		r := []rune(e.Char)
		if len(r) == 0 {
			continue
		}
		if c, ok := kangxiStrokeCorrections[r[0]]; ok {
			if e.ScienceStroke != c.CorrectedStroke {
				e.ScienceStroke = c.CorrectedStroke
				e.KangxiStroke = c.CorrectedStroke
				updated++
			}
		}
	}
	return updated
}
